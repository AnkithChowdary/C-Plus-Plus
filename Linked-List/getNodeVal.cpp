SinglyLinkedListNode* reverseList(SinglyLinkedListNode* curr,SinglyLinkedListNode* prev){
    while(curr!=NULL){
        SinglyLinkedListNode* nextnode=curr->next;
        curr->next=prev;
        prev=curr;
        curr=nextnode;
    }
    return prev;
}
int getNode(SinglyLinkedListNode* llist, int position) {
    
    SinglyLinkedListNode* prev=NULL;
  SinglyLinkedListNode* newHead=reverseList(llist,prev);
  if(position==0){
    return newHead->data;
  }
  int c=0;
  SinglyLinkedListNode* ptr=newHead;
  while(c<position){
    ptr=ptr->next;
    c++;
  }
  return (ptr!=nullptr)?ptr->data:-1;
  
  
}

